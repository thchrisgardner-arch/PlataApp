// Textos sin traducir vistos durante los recorridos (sheets, diálogos, resultados) → test-results/i18n-faltantes.txt
test.afterEach(async ({ page }) => {
  const miss: string[] = await page.evaluate(() => [...((window as unknown as { __i18nMissing?: Set<string> }).__i18nMissing ?? [])]).catch(() => [])
  const fs = await import('node:fs')
  fs.mkdirSync('test-results', { recursive: true })
  fs.appendFileSync('test-results/i18n-faltantes.txt', miss.join('\n') + '\n')
})

test('onboarding completo: permisos → teléfono → OTP (código erróneo y correcto) → passcode → Face ID', async ({ page }) => {
  await page.addInitScript(() => { if (!sessionStorage.getItem('x')) { localStorage.clear(); sessionStorage.setItem('x', '1') } })
  await page.goto('/')
  await expect(page.getByTestId('splash')).toBeVisible()
  await page.getByTestId('permissions-continue').click({ timeout: 5000 })
  await page.getByRole('button', { name: 'Continuar', exact: true }).last().click()
  await page.getByRole('button', { name: 'Permitir', exact: true }).click()
  await expect(page.getByText('Tu número de teléfono')).toBeVisible()
  await expect(page.getByTestId('phone-continue')).toBeDisabled()
  await page.keyboard.type('8429649540')
  await page.getByTestId('phone-continue').click()
  await expect(page.getByText('Ingresa el código enviado al')).toBeVisible()
  await page.keyboard.type('1111')
  await expect(page.getByRole('alert')).toHaveText('Código incorrecto')
  await page.waitForTimeout(1900)
  await page.keyboard.type('4321')
  await expect(page.getByText('Crea tu código de acceso')).toBeVisible()
  await page.keyboard.type('135790')
  await expect(page.getByText('Confirma tu código de acceso')).toBeVisible()
  await page.keyboard.type('135790')
  await page.getByTestId('faceid-later').click()
  await onScreen(page, 'home')
  expect((await state(page)).passcode).toBe('135790')
})

